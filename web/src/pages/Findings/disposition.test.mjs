import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('./disposition.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext}}).outputText;
const {canAcceptRisk,acceptanceInput}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
for(const status of ['OPEN','REOPENED','IN_PROGRESS'])assert.ok(canAcceptRisk(status));
for(const status of ['FIXED','FALSE_POSITIVE','ACCEPTED_RISK','unknown'])assert.ok(!canAcceptRisk(status));
const now=Date.parse('2026-01-01T00:00:00Z');
assert.deepEqual(acceptanceInput(' 原因 ','2026-01-02T08:00:00+08:00',now),{reason:'原因',acceptedUntil:'2026-01-02T00:00:00.000Z'});
for(const reason of ['', ' ', 'a\nb', '\u0000', '中'.repeat(167)])assert.throws(()=>acceptanceInput(reason,'2026-01-02T00:00:00Z',now));
for(const until of ['','invalid','2025-12-31T00:00:00Z','2027-01-02T00:00:00Z'])assert.throws(()=>acceptanceInput('reason',until,now));
const page=await readFile(new URL('./index.tsx',import.meta.url),'utf8');
assert.ok(page.includes('fetchFindingEvents(selectedFindingId,controller.signal)'));
assert.ok(page.includes('event.reason}</Text>'));
assert.ok(!page.includes('dangerouslySetInnerHTML'));
assert.ok(page.includes("if (!isDemoMode)"));
assert.ok(page.includes('接受风险')&&page.includes('撤销接受风险')&&page.includes('acceptanceInput(acceptReason,acceptUntil)'));
assert.ok(!page.includes("setSearchParams")||!page.includes('reason: acceptReason'));
console.log('finding disposition checks passed');
