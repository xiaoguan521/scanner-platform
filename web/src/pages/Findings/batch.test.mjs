import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('./batch.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext}}).outputText;
const {batchTransitionAllowed,batchSelectionChanged,updateBatchSelection}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
for(const from of ['OPEN','REOPENED','IN_PROGRESS']) assert.ok(batchTransitionAllowed(from,'ACCEPTED_RISK'));
for(const from of ['FIXED','FALSE_POSITIVE','ACCEPTED_RISK']) assert.ok(!batchTransitionAllowed(from,'ACCEPTED_RISK'));
assert.ok(batchTransitionAllowed('ACCEPTED_RISK','OPEN'));
assert.ok(!batchTransitionAllowed('ACCEPTED_RISK','FALSE_POSITIVE'));
assert.ok(!batchTransitionAllowed('FIXED','OPEN'));
assert.ok(!batchTransitionAllowed('OPEN','OPEN'));
assert.ok(!batchTransitionAllowed('OPEN','FIXED'));
const findings=[{id:'one',status:'OPEN'},{id:'two',status:'IN_PROGRESS'}];
let selection=updateBatchSelection([],['one'],findings);
assert.deepEqual(selection,[{id:'one',expectedStatus:'OPEN'}]);
assert.ok(!batchSelectionChanged(selection,findings));
const changed=[{id:'one',status:'IN_PROGRESS'},findings[1]];
assert.ok(batchSelectionChanged(selection,changed));
assert.ok(batchSelectionChanged(selection,[]));
selection=updateBatchSelection(selection,['one','two'],changed);
assert.deepEqual(selection,[{id:'one',expectedStatus:'OPEN'},{id:'two',expectedStatus:'IN_PROGRESS'}]);
assert.deepEqual(updateBatchSelection(selection,['two'],changed),[{id:'two',expectedStatus:'IN_PROGRESS'}]);
assert.deepEqual(updateBatchSelection(selection,[],changed),[]);
console.log('finding batch selection and transition checks passed');

assert.deepEqual(updateBatchSelection([],['unknown'],findings),[]);
const many=Array.from({length:110},(_,i)=>({id:`item-${i}`,status:'OPEN'}));
assert.equal(updateBatchSelection([],many.map(item=>item.id),many).length,100);
